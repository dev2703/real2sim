"""Portable HTML camera-quality report with local thumbnail files."""

from __future__ import annotations

import html
from pathlib import Path

import cv2
import numpy as np

THUMB_W = 320


def save_thumb(rgb: np.ndarray, path: Path, caption: str | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    h, w = rgb.shape[:2]
    scale = THUMB_W / w
    img = cv2.resize(rgb, (THUMB_W, max(1, int(round(h * scale)))), interpolation=cv2.INTER_AREA)
    bgr = cv2.cvtColor(img, cv2.COLOR_RGB2BGR)
    if caption:
        cv2.putText(bgr, caption, (4, 14), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (0, 255, 255), 1, cv2.LINE_AA)
    cv2.imwrite(str(path), bgr, [int(cv2.IMWRITE_JPEG_QUALITY), 80])


def write_montage_html(
    out_path: Path,
    dataset_title: str,
    streams: dict[str, dict],
    thumbs: dict[str, dict[int, dict[str, str]]],
    worst: dict[str, list[dict]],
) -> None:
    """Write the HTML report.

    ``streams[key]`` is the camera_quality entry (with ``label``, ``reasons``, ``episodes``).
    ``thumbs[key][ep]`` maps ``first|mid|last`` to a path relative to ``out_path.parent``.
    ``worst[key]`` is a list of ``{"path", "episode", "frame", "sharpness"}``.
    """
    css = (
        "body{font-family:system-ui,sans-serif;margin:16px;background:#fafafa;color:#222}"
        "table{border-collapse:collapse;font-size:12px}td,th{border:1px solid #ccc;padding:3px 6px;"
        "vertical-align:top}img{display:block}.USABLE{background:#dff5df}"
        ".PARTIALLY_USABLE{background:#fff3cd}.UNUSABLE{background:#f8d7da}"
        ".badge{font-weight:600;padding:2px 6px;border-radius:4px}"
        "h2{margin-top:32px}.small{color:#666;font-size:12px}"
    )
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'>",
        f"<title>Camera audit — {html.escape(dataset_title)}</title><style>{css}</style></head><body>",
        f"<h1>Camera quality audit — {html.escape(dataset_title)}</h1>",
        "<p class='small'>Generated by <code>python -m real2sim.data.audit</code>. Every thumbnail is a "
        "decoded frame from the source video at the stated episode/frame. Verdict rules and thresholds "
        "are in <code>camera_quality.json</code>.</p>",
    ]
    for key, s in streams.items():
        parts.append(f"<h2>{html.escape(key)} <span class='badge {s['label']}'>{s['label']}</span></h2>")
        parts.append("<ul>" + "".join(f"<li>{html.escape(r)}</li>" for r in s.get("reasons", [])) + "</ul>")
        info = s.get("image_info", {})
        parts.append(
            "<p class='small'>"
            + html.escape(
                f"{info.get('width')}x{info.get('height')} {info.get('video.codec', '')} "
                f"{info.get('video.fps', '')} fps; frames expected {s.get('frames_expected')}, decoded "
                f"{s.get('frames_decoded')}, decode rate {s.get('decode_rate')}, video frame deficit "
                f"{s.get('video_frame_deficit_total')}"
            )
            + "</p>"
        )
        parts.append(
            "<table><tr><th>episode</th><th>verdict</th><th>frames</th><th>sharp med</th>"
            "<th>dark</th><th>frozen</th><th>ball vis</th><th>lag</th><th>first</th><th>middle</th>"
            "<th>last</th><th>reasons</th></tr>"
        )
        for ep, e in sorted(s["episodes"].items(), key=lambda kv: int(kv[0])):
            th = thumbs.get(key, {}).get(int(ep), {})
            imgs = "".join(
                f"<td><img src='{html.escape(th[k])}' width='{THUMB_W // 2}'></td>" if k in th else "<td>—</td>"
                for k in ("first", "mid", "last")
            )
            parts.append(
                f"<tr class='{e['label']}'><td>{ep}</td><td>{e['label']}</td>"
                f"<td>{e.get('frames_decoded')}/{e.get('frames_expected')}</td>"
                f"<td>{e.get('sharpness_median', '')}</td><td>{e.get('dark_fraction', '')}</td>"
                f"<td>{e.get('frozen_fraction', '')}</td><td>{e.get('ball_visible_fraction', '')}</td>"
                f"<td>{e.get('timing_lag_frames', '')}</td>{imgs}"
                f"<td>{html.escape('; '.join(e.get('reasons', [])))}</td></tr>"
            )
        parts.append("</table>")
        if worst.get(key):
            parts.append("<h3>Lowest-sharpness frames</h3><div style='display:flex;flex-wrap:wrap;gap:6px'>")
            for w in worst[key]:
                parts.append(
                    f"<figure style='margin:0'><img src='{html.escape(w['path'])}' width='{THUMB_W // 2}'>"
                    f"<figcaption class='small'>ep {w['episode']} f {w['frame']} sharp {w['sharpness']:.2f}"
                    "</figcaption></figure>"
                )
            parts.append("</div>")
    parts.append("</body></html>")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(parts), encoding="utf-8")
